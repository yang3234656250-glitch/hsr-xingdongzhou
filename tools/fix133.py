"""tv 133（2026-11-15）：差异清单第 18 批
瓦尔特 1004 E1「终结技后，随后 2 次普攻 / 战技额外附加伤害」：
  原来 XR 表里手动勾、勾了会对所有普攻 / 战技都算，也没有「2 次」限制。
  做法：开大时挂一个「额外伤害标记」增益（复用刻律德菈那套 rx + ux/uxr：次数 2、每次开大重置），
        E1 的两条 XR 行改成只在有这个标记时才算（flag），并默认开启。

用法：python _src/fix133.py
"""
import sys
sys.path.insert(0, '_src')
from fixlib import Fix

TV = 133
F = Fix('星铁行动轴.html', TV, '_src')

F.has('r:100401', '在随后#次施放普攻或战技时额外对敌方目标造成#次附加伤害')

# ---------------- 1. 星魂 r1 加「标记」效果 ----------------
r1 = F.eid(1004, 1)
exists = [e for e in r1['eff'] if e.get('sc') == 'e1v']
assert not exists, '已经有 e1v 标记了'
r1['eff'].append({
    'y': 'dbuf', 't': 'ult', 'tg': 'self', 'm': 'rx', 'v': 1, 'sc': 'e1v', 'd': 0, 'bk': 'e1v',
    'ux': 2, 'uxr': 1,
    'n': 'E1：终结技后记录 2 次（每次普攻 / 战技用掉 1 次，用完为止；再开大重置为 2）',
})

# ---------------- 2. XR 两条改成只在标记内才算 ----------------
for key in ('e1', 'e1s'):
    row = next(x for x in F.XR['1004'] if x['k'] == key)
    row['flag'] = 'e1v'
    row.pop('off', None)
    if key == 'e1':
        row['n'] = 'E1：终结技后的 2 次普攻，额外附加普攻倍率 50% 的伤害（只在终结技后的 2 次内生效）'
    else:
        row['n'] = 'E1：终结技后的 2 次战技，额外附加战技单段倍率的 80%（只在终结技后的 2 次内生效）'

log = """<li><b>2026-11-15（差异清单第 18 批）：tv 133（tools/fix133.py）</b>。<b>瓦尔特 E1</b>「施放终结技后，瓦尔特的下 2 次普攻或战技会额外造成 1 次伤害」原来在「额外伤害」里手动勾，勾了就<b>对所有普攻 / 战技都算</b>、也没有 2 次限制；现在开大时记录 2 次（每次普攻 / 战技用掉 1 次，再开大重置），那两条额外伤害只在记录还在的时候生效，并默认开启。<b>对已有配置</b>：带 1 魂瓦尔特的方案，这条从「一直生效」变成「只有开大后 2 次攻击生效」（伤害会降），其它不变。</li>"""

record = """2026-11-15（差异清单第 18 批）：tv 133（tools/fix133.py）。改：瓦尔特 r1 加 rx 标记（sc e1v / ux 2 / uxr 1）；XR e1、e1s 两条加 flag e1v、默认开。
  未改 / 存疑：标记次数按「每次普攻 / 战技用掉 1 次」算（nxUse 的统一规则），追加攻击 / 终结技不消耗。"""

F.finish('差异清单第 18 批（瓦尔特 E1 只在终结技后 2 次内生效）', log, record)
print('done tv', TV)
