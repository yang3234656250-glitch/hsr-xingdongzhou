"""tv 147（2026-11-18）：差异清单第 24 批（白露 / 丹恒•饮月 / 寒鸦 / 彦卿）
1. 白露 1211 天赋「拥有【生息】的我方目标，在受到攻击后会回复……」：原来用触发 hit（受到攻击时，扣血之前），
   改成 hit2（受到攻击后，伤害结算后）。开了敌我掉血时以前先回血再挨打（回复会算成过量治疗）。
2. 丹恒•饮月 1213 行迹起蛰「对拥有虚数属性弱点的敌方目标造成伤害时，暴击伤害提高 24%」：原来默认关、要手动开；
   加 ec wl 虚（按受到攻击的敌人有没有虚数弱点判断）并默认开（同托帕金融动荡 tv 138 的改法）。
3. 寒鸦 1215 E6「天赋的伤害提高效果额外提高 10%」：原来是我方全体常驻 +10%（没有【承负】条件，对所有敌人都生效），
   加和天赋那条一样的 ec est 承负（只对陷入【承负】的敌人）。
4. 彦卿 1209 E6「消灭敌方目标时，如果当前持有【智剑连心】或终结技的增益效果，则使这些增益效果的持续时间全部延长 1 回合」：
   原来只延长终结技的暴击伤害（bk ultc），补上终结技的暴击率 +60%（bk ult）。

用法：python3 tools/fix147.py index.html <官方 json 目录>
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fixlib import Fix

TV = 147
F = Fix(sys.argv[1], TV, sys.argv[2])


def mig(cid, pairs, off0=True):
    """基础效果原地改：旧说明 → 新说明（off0 写旧说明：旧的默认关、新的默认开）"""
    fx = F.FIX.setdefault(str(cid), {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})
    for old, new, trig in pairs:
        fx['drop'].append(old); fx['trig'][old] = trig; fx['map'][old] = new; fx['add'].append(new)
        if off0: fx.setdefault('off0', []).append(old)


# ---------------- 1. 白露 ----------------
F.has('121104', '拥有【生息】的我方目标，在受到攻击后会回复等同于白露#生命上限+#的生命值')
z = F.eff(1211, '天赋：拥有【生息】的我方目标受到攻击后回复生命值')
assert z['t'] == 'hit' and not z.get('off'), z
old = z['n']
new = '天赋：拥有【生息】的我方目标受到攻击后（伤害结算后）回复生命值（每次获得【生息】可触发 3 次，含行迹持明龙脉 +1）'
z['t'] = 'hit2'; z['n'] = new
mig(1211, [(old, new, 'hit')], off0=False)

# ---------------- 2. 丹恒•饮月 ----------------
F.hast(1213, '起蛰', '对拥有虚数属性弱点的敌方目标造成伤害时，暴击伤害提高#')
z = F.eff(1213, '行迹起蛰：对有虚数弱点的敌人暴击伤害 +24%')
assert z.get('off') and z['t'] == 'start' and not z.get('ec'), z
old = z['n']
new = '行迹起蛰：对拥有虚数属性弱点的敌方目标造成伤害时暴击伤害 +24%（按受到攻击的敌人的弱点判断，默认开启；没放敌人卡时不算）'
z.pop('off'); z['ec'] = {'wl': '虚'}; z['n'] = new
mig(1213, [(old, new, 'start')])

# ---------------- 3. 寒鸦 ----------------
F.has('r:121506', '天赋的伤害提高效果额外提高#')
tal = F.eff(1215, '天赋：我方对【承负】的敌人施放普攻、战技、终结技时伤害 +30%')
assert tal.get('ec') == {'est': '承负'}
e6 = F.eid(1215, 6)
assert len(e6['eff']) == 1 and e6['eff'][0]['n'] == 'E6：天赋的增伤额外 +10%' and not e6['eff'][0].get('ec'), e6
z = e6['eff'][0]
z['ec'] = {'est': '承负'}
z['n'] = 'E6 六正：天赋的伤害提高效果额外 +10%（和天赋一样只对陷入【承负】的敌人）'

# ---------------- 4. 彦卿 ----------------
F.has('r:120906', '消灭敌方目标时，如果当前持有【智剑连心】或终结技的增益效果，则使这些增益效果的持续时间全部延长#回合')
ucr = F.eff(1209, '终结技：暴击率 +60%，持续 1 回合')
assert ucr['bk'] == 'ult' and ucr['m'] == 'cr' and ucr['d'] == 1 and not ucr.get('cnt')
e6 = F.eid(1209, 6)
assert len(e6['eff']) == 2 and e6['eff'][1].get('dx') == 1 and e6['eff'][1]['bk'] == 'ultc'
e6['eff'][1]['n'] = 'E6：消灭敌方目标时终结技的暴击伤害增益延长 1 回合（只延长已有的）'
e6['eff'].append({'y': 'dbuf', 't': 'kill', 'tg': 'self', 'm': 'cr', 'v': 60, 'd': 1, 'bk': 'ult', 'dx': 1,
                  'n': 'E6：消灭敌方目标时终结技的暴击率增益同样延长 1 回合（只延长已有的）'})

log = """<li><b>2026-11-18（差异清单第 24 批）：tv 147（tools/fix147.py）</b>。依据官方原文（Mar-7th character_skills / skill_trees / ranks）。① <b>白露天赋</b>「拥有【生息】的我方目标，在<b>受到攻击后</b>会回复……」原来用“受到攻击时”（扣血之前）触发，改成“受到攻击后”（伤害结算后）；开了敌我掉血时以前先回血再挨打，回复会算成过量治疗。② <b>丹恒•饮月行迹起蛰</b>（对拥有虚数弱点的敌人暴击伤害 +24%）原来默认关，现在按受到攻击的敌人有没有虚数弱点判断、默认开（没放敌人卡时不算）。③ <b>寒鸦 E6</b>「天赋的伤害提高效果额外提高 10%」原来是对所有敌人常驻 +10%，现在和天赋一样只对陷入【承负】的敌人。④ <b>彦卿 E6</b>「消灭敌人时【智剑连心】或终结技的增益全部延长 1 回合」原来只延长终结技的暴击伤害，补上终结技的暴击率。<b>对已有配置</b>：行动顺序不变（只有白露那条在敌人攻击时先后换了，不开敌我掉血时治疗量也不变）；其余只影响伤害显示。老存档里起蛰原来关着的会按新默认打开。</li>"""

record = """2026-11-18（差异清单第 24 批）：tv 147（tools/fix147.py）。改：白露天赋生息回复 hit → hit2；丹恒•饮月起蛰 ec wl 虚、默认开；寒鸦 E6 加 ec est 承负；彦卿 E6 补终结技暴击率 dx（bk ult）。
  存疑：寒鸦天赋原文“造成的伤害提高 30%，持续 2 回合”，页面是对【承负】敌人常驻（没有“持续 2 回合”），已记进差异清单。"""

F.finish('差异清单第 24 批（白露天赋 hit2、丹恒•饮月起蛰、寒鸦 E6、彦卿 E6）', log, record)
print('done tv', TV)
