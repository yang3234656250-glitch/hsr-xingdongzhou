"""tv 128（2026-11-15）：差异清单第 13 批
桑博 1108 E2「风化状态下的敌方目标被消灭时，使敌方全体叠加 1 层风化」：
  原来挂在消灭事件上，但没判断被消灭的敌人有没有风化（任何敌人被消灭都算）。
  用 tv 122 加的 killDot 判据修（模板字段 kd）。

用法：python _src/fix128.py
"""
import sys
sys.path.insert(0, '_src')
from fixlib import Fix

TV = 128
F = Fix('星铁行动轴.html', TV, '_src')

F.has('r:110802', '风化状态下的敌方目标被消灭时，使敌方全体有#的基础概率叠加#层等同于天赋的风化状态')

e = F.eff(1108, 'E2：风化的敌方目标被消灭时', r=2)
old = e['n']
e['kd'] = '风化'
e['n'] = 'E2：风化状态下的敌方目标被消灭时，使敌方全体叠加 1 层风化（开了「我方伤害扣敌人生命值」时自动触发；只算身上有风化的敌人被消灭）'
fx = F.FIX.setdefault('1108', {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})
fx['drop'].append(old)
fx['add'].append(e['n'])
fx['trig'][old] = 'kill'
fx['map'][old] = e['n']

log = """<li><b>2026-11-15（差异清单第 13 批）：tv 128（tools/fix128.py）</b>。<b>桑博 E2</b>「风化状态下的敌方目标被消灭时，使敌方全体叠加 1 层风化」原来不管被消灭的敌人身上有没有风化，任何敌人被消灭都算；现在按「被消灭的敌人有风化」判断（用 tv 122 加的消灭事件判据）。<b>对已有配置</b>：只有开了「我方伤害扣敌人生命值」、并且被消灭的敌人身上确实有风化时才会叠层；其他情况不变。</li>"""

record = """2026-11-15（差异清单第 13 批）：tv 128（tools/fix128.py）。改：桑博 E2 加 kd 风化（killDot）。
  未改 / 存疑：桑博行迹加料「风化状态下的敌方目标对桑博造成的伤害降低 15%」仍然没做（这是「受到的伤害降低」，要按攻击者身上有没有风化判断，目前 dr 这类增益没有按敌人状态取条件的通道）。"""

F.finish('差异清单第 13 批（桑博 E2 只算风化的敌人被消灭）', log, record)
print('done tv', TV)
