"""tv 115：差异清单第三类 4 条——娜塔莎 E1 改成受到攻击后（hit2）判断生命值、佩拉 E4 冰抗降低只算冰属性攻击、
克拉拉终结技受到的伤害额外降低 25%（2 回合）、“消灭敌人时”几条效果的说明（开了敌人掉血后自动触发）。
引擎：效果里字符串形式的 tEl（tel 属性字）不再走“只对欢愉 / 非欢愉目标”的判断（那条只给数字形式的 te 用）。
用法：python3 tools/fix115.py index.html <官方 json 目录>"""
import sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from fixlib import Fix
F = Fix(sys.argv[1], 115, sys.argv[2])
C, has = F.C, F.has

# ---- 引擎：tel（属性字）和 te（欢愉 1 / -1）共用 tEl 字段，施加时只有数字形式才按目标是不是欢愉角色筛 ----
F.rep('''        if (eff.tEl && !!(tg && tg.elation) !== (num(eff.tEl) > 0)) continue;   // 只对欢愉 / 非欢愉角色''',
      '''        if (eff.tEl && /^-?\\d/.test(String(eff.tEl)) && !!(tg && tg.elation) !== (num(eff.tEl) > 0)) continue;   // 只对欢愉 / 非欢愉角色（属性字形式的 tEl 是“只对这些属性的攻击”，不在这里筛）''')

def find(L, pre):
    R = [e for e in L if (e.get('n') or '').startswith(pre)]; assert len(R) == 1, (pre, [e.get('n') for e in R]); return R[0]

# ---- 娜塔莎 E1：受到攻击后（扣血之后）判断当前生命值 ≤30% ----
has('r:110501', '受到攻击后，若当前生命值百分比小于等于30%，对自身施放1次治疗，回复等同于自身15%生命上限+400的生命值。该效果单场战斗中只能触发1次')
e1 = F.eid(1105, 1); x = find(e1['eff'], 'E1 遍识药理'); assert x['t'] == 'hit' and x.get('hle') == 30
x['t'] = 'hit2'
x['n'] = 'E1 遍识药理：受到攻击后若当前生命值 ≤30%（按挨打之后的生命值），对自身施放 1 次治疗，回复 15% 生命上限 +400（每场 1 次）'

# ---- 佩拉 E4：冰属性抗性降低只对冰属性攻击生效 ----
has('r:110604', '施放战技时，有100%的基础概率使敌方目标冰属性抗性降低12%，持续2回合')
e4 = F.eid(1106, 4); x = find(e4['eff'], 'E4：施放战技时敌人冰属性抗性'); assert x['m'] == 'resRed' and x['v'] == 12 and x['d'] == 2
x['tel'] = '冰'
x['n'] = 'E4 完全剖析：施放战技时敌人冰属性抗性 −12%，持续 2 回合（只对冰属性攻击生效）'

# ---- 克拉拉终结技：受到的伤害额外降低 25%（12 级 27%），持续 2 回合 ----
has('110703', '施放终结技后克拉拉受到的伤害额外降低#4[i]%且被敌方目标攻击的概率大幅提高，持续#3[i]回合')
p10, p12 = F.prm('110703', 10), F.prm('110703', 12)
assert (p10[2], p12[2]) == (2, 2), (p10, p12)
v10, v12 = round(p10[3] * 100, 4), round(p12[3] * 100, 4); assert (v10, v12) == (25, 27), (v10, v12)
assert F.RK['110705']['level_up_skills'][0]['id'] == '110703'   # 5 魂终结技 +2 级
c = C[1107]; new = list(c['eff'])
i = next(k for k, e in enumerate(new) if (e.get('n') or '').startswith('额外伤害标记：【强化反击】期间'))
new.insert(i, dict(y='dbuf', t='ult', tg='self', m='dr', v=v10, lv=[5, v12], d=2, bk='ultdr',
                   n=f'终结技：施放终结技后克拉拉受到的伤害额外降低 {v10:g}%（5 魂 {v12:g}%），持续 2 回合（“被敌方攻击的概率大幅提高”没做）'))
F.rebuild(1107, new)

# ---- “消灭敌人时”的说明：开了“我方伤害扣敌人生命值”后 killEnemy 自动 fireEv("kill", 击杀者)，ew any 的都会触发 ----
SW = '开了“我方伤害扣敌人生命值”时自动触发，没开用手动消灭事件'
def ren_eid(cid, r, pre, n):
    e = F.eid(cid, r); x = find(e['eff'], pre); assert x['t'] == 'kill'; x['n'] = n
has('r:110802', '风化')
ren_eid(1108, 2, 'E2：风化的敌方目标被消灭时', f'E2：风化的敌方目标被消灭时，敌方全体叠加 1 层风化（{SW}；没判断被消灭的敌人有没有风化，任何敌人被消灭都算）')
ren_eid(1202, 2, 'E2 君子惠渥', f'E2 君子惠渥，晏笑承之：得到【赐福】的我方单体消灭敌方目标时 +5 能量（每回合 1 次；{SW}）')
ren_eid(1307, 2, 'E2：【奥迹】状态下的敌方目标被消灭时', f'E2：【奥迹】状态下的敌方目标被消灭时，相邻目标陷入 6 层【奥迹】（{SW}；没判断被消灭的敌人有没有【奥迹】；相邻按第 2、3 个敌人）')
c = C[1315]; x = find(c['eff'], '战技：【绝命对峙】的目标被消灭或弱点被击破后获得 1 层【优势口袋】'); o = x['n']
x['n'] = n = f'战技：【绝命对峙】的目标被消灭或弱点被击破后获得 1 层【优势口袋】（最多 3 层；消灭：{SW}；没判断被消灭的是不是【绝命对峙】的目标）'
F.rebuild(1315, c['eff'], rename={o: n})

F.finish('差异清单：娜塔莎 E1、佩拉 E4、克拉拉终结技减伤、消灭敌人说明', '''<li><b>2026-11-15（差异清单）</b>：tv 115（tools/fix115.py）。按官方原文：娜塔莎 1 魂“受到攻击后，若当前生命值百分比 ≤30%”改成在挨打之后判断（原来用的是挨打之前的生命值，开了敌人伤害时会漏触发）；佩拉 4 魂“冰属性抗性降低 12%”只对冰属性的攻击生效（原来所有属性都吃）；克拉拉终结技补上“施放终结技后受到的伤害额外降低 25%（5 魂 27%），持续 2 回合”（“被攻击概率大幅提高”仍没做）；桑博 / 停云 / 黑天鹅 2 魂、波提欧战技里“消灭敌人时”的说明改成：开了“我方伤害扣敌人生命值”就会自动触发（以前写着要手动加事件）。没开敌人伤害时行动轴不变；佩拉 4 魂只影响伤害显示。</li>''',
'''2026-11-15：差异清单 —— tv 115（tools/fix115.py）。娜塔莎 E1 hit → hit2；佩拉 E4 tel 冰；克拉拉终结技 dr 25%（lv [5, 27]）d 2；桑博 E2、停云 E2、黑天鹅 E2、波提欧【优势口袋】说明（kill 在开了敌人掉血后自动触发）。引擎：字符串 tEl 不再按欢愉目标筛。
  未改 / 存疑：桑博 E2、黑天鹅 E2 没判断被消灭的敌人有没有风化 / 奥迹，波提欧没判断被消灭的是不是对峙目标（kill 的事件对象是击杀者；要用 ekill 改写）''')
