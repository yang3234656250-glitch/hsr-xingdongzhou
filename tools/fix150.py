"""tv 150（2026-11-20）：差异清单第 26 批（银枝 E2 / 慷慨、阮•梅落烛照水燃 / E2、砂金【惊惶】 / 杠杆）
1. 银枝 1302
   - E2 玛瑙石的谦卑“施放终结技时，若敌方目标数量大于等于3个时，攻击力提高40%，持续1回合”：以前默认关、要自己开；
     改成按场上在场敌人数自动判断（伤害增益字段 ven [0, 0, 40, 40, 40]，tv 69 起就有），默认开。
   - 行迹慷慨“在敌方目标进入战斗时，自身立即恢复2点能量”：以前按 1 个敌人在战斗开始时 +2；
     新触发 eIn（敌方目标进入战斗时，事件对象 = 这个敌人）：战斗开始时场上每个敌人各触发 1 次，之后登场 / 重新登场的敌人（reviveEnemy）再触发；
     没放敌人卡时战斗开始触发 1 次（“没放敌人按 1 个”）。转阶段不算进入战斗。
2. 阮•梅 1303
   - 行迹落烛照水燃“战斗中阮•梅的击破特攻大于120%时，每超过10%，则战技使我方全体伤害提高的效果额外提高6%，最高不超过36%”：
     以前按满额 36% 默认关；改成按战斗中的击破特攻算（新字段 sbt → srcBt：srcS be 时用 beOf + beTeam = 卡片 + 自身增益 + 全队增益），
     数值 = ⌊击破特攻 / 10⌋ × 10 × 60% − 72，0～36，出手时重算（dy），默认开。
   - E2 芦前漫步“阮•梅在场时，我方全体对处于弱点击破状态的敌方目标造成伤害时，攻击力提高40%”：以前默认关；加 ec brk（tv 85 起有），默认开。
3. 砂金 1304
   - 终结技“使指定敌方单体陷入【惊惶】状态，持续3回合……我方目标击中【惊惶】状态下的敌方目标时，造成的暴击伤害提高15%”：
     以前是我方全体 3 回合常驻 +15%（打哪个敌人都算）；改成主目标挂状态【惊惶】3 回合（敌人自己的回合），增益常驻但带 ec est 惊惶。
   - 行迹杠杆（新发现）：数值写成 v 0.02（按“每点防御力 0.02%”），但 dbAmt 是 属性 × v / 100，算出来永远 ≤0 → 暴击率一直 +0；改成 v 2。

用法：python3 tools/fix150.py index.html <官方 json 目录>
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fixlib import Fix

TV = 150
F = Fix(sys.argv[1], TV, sys.argv[2])


def fix_of(cid):
    return F.FIX.setdefault(str(cid), {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})


def swap(cid, oldn, oldt, newn_list, mapto, off0=False):
    fx = fix_of(cid)
    fx['drop'].append(oldn); fx['trig'][oldn] = oldt; fx['map'][oldn] = mapto; fx['add'] += newn_list; fx['keep'] = 1
    if off0: fx.setdefault('off0', []).append(oldn)


# ---------------- 引擎 ----------------
F.rep('      if (x.ss) e.srcS = x.ss;                    // 伤害增益：数值按施放者哪项属性算',
      '      if (x.ss) e.srcS = x.ss;                    // 伤害增益：数值按施放者哪项属性算\n'
      '      if (x.sbt) e.srcBt = 1;                     // 属性按战斗中的（击破特攻：卡片 + 自身增益 + 全队增益；阮•梅落烛照水燃）')
F.rep('        if (k === "el") for (const b of',
      '        if (k === "be" && eff.srcBt) x = beOf(o) + beTeam();   // srcBt：战斗中的击破特攻（阮•梅落烛照水燃）\n'
      '        if (k === "el") for (const b of')
F.rep('      swqFire("进战");\n',
      '      { const EN = U.filter(z => z.kind === "enemy" && !z.gone); if (EN.length) for (const en of EN) fireAll("eIn", en); else if (!U.some(z => z.kind === "enemy")) fireAll("eIn", null); }   // 敌方目标进入战斗时（每个敌人 1 次；没放敌人卡按 1 个；进战秘技之后才召唤的在登场时）\n'
      '      swqFire("进战");\n')
i = F.s.index('      addLog(first ? `${en.name} 登场')
j = F.s.index('\n', i)
F.s = F.s[:j + 1] + '      fireAll("eIn", en);   // 敌方目标进入战斗时（登场 / 重新登场；银枝慷慨）\n' + F.s[j + 1:]
F.rep('"ekill", "hit", "hit2"', '"ekill", "eIn", "hit", "hit2"')
F.rep('ekill: "敌人被消灭时", ', 'ekill: "敌人被消灭时", eIn: "敌方目标进入战斗时", ')
F.rep('["ekill", "敌人被消灭时"]', '["ekill", "敌人被消灭时"], ["eIn", "敌方目标进入战斗时"]', 2)

# ---------------- 1. 银枝 ----------------
F.has('r:130202', '施放终结技时，若敌方目标数量大于等于3个时，攻击力提高40%，持续1回合')
F.hast(1302, '慷慨', '在敌方目标进入战斗时，自身立即恢复#点能量')
e2 = [z for z in F.eid(1302, 2)['eff'] if z.get('bk') == 'e2']; assert len(e2) == 1
e2 = e2[0]; assert e2['v'] == 40 and e2.get('off') and e2['t'] == 'ult' and e2['d'] == 1
del e2['off']; e2['ven'] = [0, 0, 40, 40, 40]
e2['n'] = 'E2 玛瑙石的谦卑：施放终结技时，若敌方目标数量 ≥3 个（按场上在场的敌人数），攻击力 +40%，持续 1 回合'
kk = F.eff(1302, '行迹慷慨')
assert kk['t'] == 'start' and kk['v'] == 2 and kk['y'] == 'energy'
oldn = kk['n']
kk['t'] = 'eIn'
kk['n'] = '行迹慷慨：敌方目标进入战斗时恢复 2 点能量（场上每个敌人各 1 次，之后登场 / 重新登场的敌人也算；没放敌人卡按 1 个）'
swap(1302, oldn, 'start', [kk['n']], kk['n'])

# ---------------- 2. 阮•梅 ----------------
F.hast(1303, '落烛照水燃', '战斗中阮•梅的击破特攻大于#时，每超过#，则战技使我方全体伤害提高的效果额外提高#，最高不超过#')
F.has('r:130302', '阮•梅在场时，我方全体对处于弱点击破状态的敌方目标造成伤害时，攻击力提高40%')
lz = F.eff(1303, '行迹落烛照水燃')
assert lz['v'] == 36 and lz.get('off') and lz['t'] == 'skill' and lz['bk'] == 'st:弦外音#lz'
oldn = lz['n']
del lz['off']
lz.update(v=60, ss='be', sbt=1, hf=-72, cap=36, stp=10, dy=1,
          n='行迹落烛照水燃：阮•梅拥有【弦外音】时，战斗中击破特攻大于 120% 的部分每 10% 使弦外音的我方全体增伤额外 +6%，最多 +36%（按卡片击破特攻 + 战斗中的击破特攻增益，出手时算）')
swap(1303, oldn, 'skill', [lz['n']], lz['n'], off0=True)
r2 = [z for z in F.eid(1303, 2)['eff'] if z.get('bk') == 'e2']; assert len(r2) == 1
r2 = r2[0]; assert r2['v'] == 40 and r2.get('off') and r2['m'] == 'atkP'
del r2['off']; r2['ec'] = {'brk': 1}
r2['n'] = 'E2 芦前漫步：阮•梅在场时，我方全体对处于弱点击破状态的敌方目标造成伤害时攻击力 +40%（按受到攻击的敌人是否处于击破状态）'

# ---------------- 3. 砂金 ----------------
F.has('130403', '随后使指定敌方单体陷入【惊惶】状态，持续#回合')
F.has('130403', '我方目标击中【惊惶】状态下的敌方目标时，造成的暴击伤害提高#')
assert F.prm('130403', 10)[3] == 3 and F.prm('130403', 10)[2] == 0.15 and F.prm('130403', 12)[2] == 0.162
F.hast(1304, '杠杆', '若砂金的防御力高于#点，每超过100点防御力可使自身暴击率提高#，最多提高#')
c = F.C[1304]
jh = F.eff(1304, '终结技：我方击中【惊惶】')
assert jh['t'] == 'ult' and jh['tg'] == 'team' and jh['d'] == 3 and jh['v'] == 15
oldn = jh['n']
st = {'y': 'state', 't': 'ult', 'tg': 'efirst', 'sn': '惊惶', 'v': 1, 'd': 3,
      'n': '终结技：使指定敌方单体（主目标）陷入【惊惶】状态，持续 3 回合（按敌人自己的回合）'}
jh.update(t='start', d=0, ec={'est': '惊惶'},
          n='终结技：我方目标击中【惊惶】状态下的敌方目标时，暴击伤害 +15%（3 魂 16.2%；按受到攻击的敌人身上有没有【惊惶】）')
c['eff'].insert(c['eff'].index(jh), st)
swap(1304, oldn, 'ult', [st['n'], jh['n']], jh['n'])
gg = F.eff(1304, '行迹杠杆')
assert gg['v'] == 0.02 and gg['hf'] == -32 and gg['stp'] == 100 and gg['cap'] == 48
oldn = gg['n']
gg['v'] = 2
gg['n'] = '行迹杠杆：防御力超过 1600 时每超过 100 点暴击率 +2%，最多 +48%（按卡片面板防御力）'
assert gg['n'] == oldn
gg['n'] = '行迹杠杆：防御力高于 1600 点时，每超过 100 点暴击率 +2%，最多 +48%（按卡片面板防御力）'
swap(1304, oldn, 'start', [gg['n']], gg['n'])

log = """<li><b>2026-11-20（差异清单第 26 批）：tv 150（tools/fix150.py）</b>。依据官方原文（Mar-7th character_skills / skill_trees / ranks）。① <b>银枝 E2</b>“施放终结技时，若敌方目标数量大于等于 3 个，攻击力提高 40%，持续 1 回合”：以前默认关，现在按场上在场的敌人数自动判断、默认开。<b>银枝行迹慷慨</b>“在敌方目标进入战斗时，自身立即恢复 2 点能量”：新触发「敌方目标进入战斗时」，战斗开始时每个敌人各 1 次、之后登场 / 重新登场的敌人也算（没放敌人卡按 1 个）；以前不管几个敌人都只 +2。② <b>阮•梅行迹落烛照水燃</b>“战斗中击破特攻大于 120% 时，每超过 10%，战技增伤额外提高 6%，最高 36%”：改成按战斗中的击破特攻（卡片 + 击破特攻增益，含物体呼吸中、E4）在出手时算，默认开（以前按满额、默认关）；<b>E2</b>“对处于弱点击破状态的敌方目标攻击力 +40%”按敌人实际击破状态，默认开。③ <b>砂金终结技【惊惶】</b>：主目标陷入【惊惶】3 回合，暴击伤害 +15% 只在打有【惊惶】的敌人时算（以前全队 3 回合打谁都算；没放敌人卡时不算）。<b>砂金行迹杠杆</b>修正：数值写错（每 100 点防御力的 2% 被除了 100），以前暴击率一直 +0，现在按卡片防御力正常算。<b>对已有配置</b>：只有银枝（慷慨按敌人数回能，敌人多时开大会提前）会改变行动顺序；其他都只影响伤害显示。老存档的这几张卡按新模板换掉对应效果，原来开着的保持开着；落烛照水燃、两个 E2 改成默认开。</li>"""

record = """2026-11-20（差异清单第 26 批）：tv 150（tools/fix150.py）。改：银枝 E2 ven [0,0,40,40,40] 默认开、慷慨新触发 eIn（敌方目标进入战斗时）；阮•梅落烛照水燃 ss be + sbt（战斗中击破特攻）v 60 hf −72 stp 10 cap 36 dy、E2 ec brk 默认开；砂金终结技【惊惶】= efirst 状态 3 回合 + 暴伤 ec est、行迹杠杆 v 0.02 → 2（以前算出来恒为 0）。
  存疑：阮•梅卡片击破特攻如果照角色面板填、面板里已经含物体呼吸中的 20%，会和全队增益重复算（落烛照水燃会偏高一档）；银枝慷慨“进入战斗”按开局在场 + 登场 / 重新登场，转阶段不算。"""

F.finish('差异清单第 26 批（银枝 E2 / 慷慨、阮•梅落烛照水燃 / E2、砂金惊惶 / 杠杆）', log, record)
