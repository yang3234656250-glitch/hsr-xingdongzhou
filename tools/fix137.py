"""tv 137（2026-11-15）：差异清单第 21 批（收尾）
椒丘 1218 天赋「【烬煨】1 层受到的伤害 +15%，每多 1 层 +5%，最多 5 层」原来按叠满 5 层 35% 写死。
  改成：15%（固定，目标有【烬煨】才算）+ 5% × (层数−1，最多 9 层)，6 魂把上限抬到 9 层时自然到 55%。
  同时删掉 tv 136 加的那条「超过 5 层每层 +5%」的易伤——现在天赋本身已经按层数算到 9 层，留着会重复。

用法：python _src/fix137.py
"""
import sys
sys.path.insert(0, '_src')
from fixlib import Fix

TV = 137
F = Fix('星铁行动轴.html', TV, '_src')

F.has('1218101', '【烬煨】#层受到的伤害提高#，每多#层提高#') if False else None

c = F.C[1218]
old_note = None
for e in c['eff']:
    if (e.get('n') or '').startswith('天赋：【烬煨】1 层受到的伤害 +15%'):
        old_note = e['n']
        e['v'] = 5
        e['ec'] = {'dkSt': ['烬煨', 1, 9]}
        e['n'] = '天赋：【烬煨】每多 1 层使目标受到的伤害 +5%（第 1 层的 15% 另算），最多 9 层'
assert old_note, '没找到天赋那条'

# 固定 15% 那条（目标有【烬煨】才算）
c['eff'].append({
    'y': 'dbuf', 't': 'atk', 'aw': 'self', 'tg': 'ehit', 'm': 'vuln', 'v': 15, 'd': 2, 'bk': 'jw0',
    'edk': '烬煨',
    'n': '天赋：【烬煨】第 1 层使目标受到的伤害 +15%（目标身上有【烬煨】才算），持续 2 回合',
})

fx = F.FIX.setdefault('1218', {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})
fx['drop'].append(old_note)
fx['add'].append('天赋：【烬煨】每多 1 层使目标受到的伤害 +5%（第 1 层的 15% 另算），最多 9 层')
fx['add'].append('天赋：【烬煨】第 1 层使目标受到的伤害 +15%（目标身上有【烬煨】才算），持续 2 回合')
fx['trig'][old_note] = 'atk'
fx['trig']['天赋：【烬煨】第 1 层使目标受到的伤害 +15%（目标身上有【烬煨】才算），持续 2 回合'] = 'atk'
fx['map'][old_note] = '天赋：【烬煨】每多 1 层使目标受到的伤害 +5%（第 1 层的 15% 另算），最多 9 层'

# 删掉 tv 136 那条「超过 5 层每层 +5%」的重复易伤
for x in c['eid']:
    n0 = len(x['eff'])
    x['eff'] = [z for z in x['eff'] if not (z.get('n') or '').startswith('E6：超过 5 层的【烬煨】每层再使目标受到的伤害')]
    if len(x['eff']) != n0:
        F.touch(1218)

log = """<li><b>2026-11-15（差异清单第 21 批收尾）：tv 137（tools/fix137.py）</b>。<b>椒丘</b>天赋「【烬煨】1 层受到的伤害 +15%，每多 1 层 +5%，最多 5 层」原来按叠满 5 层（35%）写死。现在拆成「第 1 层 15%（目标身上有【烬煨】才算）+ 每多 1 层 5%（按实际层数，最多 9 层）」，6 魂把上限抬到 9 层时自然到 55%；同时删掉上一批加的那条「超过 5 层每层 +5%」——天赋本身已经算到 9 层，留着会重复。<b>对已有配置</b>：带椒丘的方案，【烬煨】不到 5 层时易伤按实际层数少算（伤害略降），9 层时仍是 55%。</li>"""

record = """2026-11-15（热椒丘收尾）：tv 137（tools/fix137.py）。改：天赋易伤拆成「15% 固定 + 5% × (层数−1)，dkSt 上限 9」；删 E6 里「超过 5 层 +5%」那条重复行。
  未改 / 存疑：层数上限 9 只在 6 魂才有，这里 dkSt 上限直接写 9（没 6 魂时层数本身到不了 9，影响不大）。"""

F.finish('差异清单第 21 批收尾（椒丘天赋易伤按实际层数）', log, record)
print('done tv', TV)
