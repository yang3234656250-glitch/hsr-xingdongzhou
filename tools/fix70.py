"""tv 70：击破第 3 批（雪衣 1214、飞霄 1220、黄泉 1308、灵砂 1222、Archer 1015、那刻夏 1405 的无视弱点削韧 / 击破效率 / 添加弱点）。
用法：python3 tools/fix70.py index.html <官方 json 目录>。没有引擎改动，全部用 tv 69 的 tig / befU / bef / weak。"""
import sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from fixlib import Fix, r4
F = Fix(sys.argv[1], 70, sys.argv[2])
C, prm, has, hast = F.C, F.prm, F.has, F.hast
def lvE(cid, base):
    for r in range(1, 7):
        for z in (F.RK[str(cid * 100 + r)].get('level_up_skills') or []):
            if str(z.get('id')) == str(base): return r
    raise KeyError(base)
D = lambda **k: dict(dict(y='dbuf', d=0, t='start', tg='self'), **k)

# 雪衣
has('121403', '本次攻击无视弱点属性削减敌方单体的韧性'); has('r:121402', '天赋的追加攻击无视弱点属性削减敌方的韧性')
F.rebuild(1214, list(C[1214]['eff']) + [D(m='tig', v=100, sc='u', bk='ut', n='终结技：本次攻击无视弱点属性削减敌方单体的韧性')])
e2 = F.eid(1214, 2); e2['eff'] = e2.get('eff', []) + [D(m='tig', v=100, sc='f', bk='e2t', n='E2：天赋的追加攻击无视弱点属性削减敌方的韧性')]

# 飞霄
has('122003', '期间可无视弱点属性削减目标韧性，目标未处于弱点击破状态时飞霄的弱点击破效率提高#2[i]%'); assert prm('122003', 10)[1] == 1 and prm('122003', 12)[1] == 1
F.rebuild(1220, list(C[1220]['eff']) + [
    D(m='tig', v=100, sc='u', bk='ut', n='终结技：期间可无视弱点属性削减目标韧性'),
    D(m='befU', v=100, sc='u', bk='ub', n='终结技：目标未处于弱点击破状态时飞霄的弱点击破效率 +100%')])

# 黄泉
has('130804', '终结技期间可无视弱点属性削减敌方韧性'); has('r:130806', '施放普攻、战技造成的伤害同时视为终结技伤害，并无视弱点属性削减敌方韧性')
F.rebuild(1308, list(C[1308]['eff']) + [D(m='tig', v=100, sc='u', bk='ut', n='天赋：终结技期间可无视弱点属性削减敌方韧性')])
e6 = F.eid(1308, 6); e6['eff'] = e6.get('eff', []) + [
    D(m='tig', v=100, sc='b', bk='e6tb', n='E6：普攻无视弱点属性削减敌方韧性'), D(m='tig', v=100, sc='s', bk='e6ts', n='E6：战技无视弱点属性削减敌方韧性')]

# 灵砂
has('122203', '使目标受到的击破伤害提高#4[i]%，持续#5[i]回合'); has('r:122201', '灵砂的弱点击破效率提高50%'); has('r:122202', '使我方全体击破特攻提高40%，持续3回合')
eu = lvE(1222, 122203); u10, u12 = prm('122203', 10), prm('122203', 12); assert r4(u10[3]) == 0.25 and r4(u12[3]) == 0.27 and u10[4] == 2
F.rebuild(1222, list(C[1222]['eff']) + [dict(y='dbuf', t='ult', tg='enemies', m='vuln', sc='k', v=25, lv=[eu, 27], d=2, bk='cz', n='终结技：敌方全体陷入【醇醉】，受到的击破伤害 +25%%（%d 魂 27%%），持续 2 回合' % eu)], notes=[])
e1 = F.eid(1222, 1); e1['eff'] = e1.get('eff', []) + [D(m='bef', v=50, bk='e1b', n='E1：灵砂的弱点击破效率 +50%')]
for e in e1['eff']:
    if '需要时启用' in (e.get('n') or ''): e['n'] = 'E1：敌人被击破时防御力 −20%（持续到恢复韧性；现在会自动触发，原文是被击破的那个敌人，这里按敌方全体，需要时启用）'
e2 = F.eid(1222, 2); e2['eff'] = e2.get('eff', []) + [dict(y='dbuf', t='ult', tg='team', m='be', v=40, d=3, bk='e2', n='E2：施放终结技时我方全体击破特攻 +40%，持续 3 回合')]

# Archer
has('r:101502', '并为其添加量子属性弱点，持续2回合')
e2 = F.eid(1015, 2); e2['eff'] = e2.get('eff', []) + [dict(y='weak', t='ult', tg='efirst', wel='量', d=2, bk='wk', n='E2：施放终结技时为敌方目标添加量子属性弱点，持续 2 回合')]

# 那刻夏
has('140503', '目标同时被添加物理、火、冰、雷、风、量子、虚数属性弱点，持续至目标回合开始时')
F.rebuild(1405, list(C[1405]['eff']) + [dict(y='weak', t='ult', tg='enemies', wel='all', d=1, bk='sh', n='终结技：敌方全体陷入【升华】，同时被添加全部 7 种属性弱点，持续至目标回合开始时')],
          notes=['战技“场上每有 1 个可攻击的敌方目标伤害 +20%”、天赋每次击中添加 1 个随机属性弱点、【升华】下无法行动没做'])

