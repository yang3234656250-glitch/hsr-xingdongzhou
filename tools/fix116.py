"""tv 116（2026-11-15）：差异清单第 1 批（接在仓库 tv 115 之后）
① 姬子 1003 行迹星火：挂灼烧从「敌方全体」改成「这次攻击打到的敌人」（ehit）
② 卡芙卡 1005 E1：持续伤害易伤从「敌方全体」改成「追加攻击的目标」（efirst）
③ 瓦尔特 1004 天赋【失重】：速度 −5% 从默认关改成默认开（原文是【失重】必定挂上）

昨天先在本地 tv 115 上做过一遍，仓库当晚也推了它自己的 tv 115（娜塔莎 / 佩拉 / 克拉拉 / 桑博说明），
所以这里以仓库 tv 115 为底重新做一遍，版本号顺延到 116。
用法：python _src/fix116.py
"""
import sys
sys.path.insert(0, '_src')
from fixlib import Fix

TV = 116
F = Fix('星铁行动轴.html', TV, '_src')


def rename_eff(cid, frag, r=None, off0=None, drop_off=False, **chg):
    e = F.eff(cid, frag, r=r)
    old = e['n']
    trig = e.get('t')
    e.update(chg)
    if drop_off:
        e.pop('off', None)
    new = e['n']
    fx = F.FIX.setdefault(str(cid), {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})
    fx['drop'].append(old)
    fx['add'].append(new)
    fx['trig'][old] = trig
    if new != old:
        fx['map'][old] = new
    if off0:
        fx.setdefault('off0', []).append(new)
    return old, new


# ① 姬子：星火按打到的敌人挂灼烧
F.hast(1003, '星火', '施放攻击后，有#的基础概率使敌方目标陷入灼烧状态，持续#回合')
rename_eff(
    1003, '行迹星火',
    tg='ehit',
    n='行迹星火：施放攻击后使被打到的敌人陷入灼烧（单体只挂主目标，扩散挂主目标和相邻，群攻挂全体），每回合开始受到 30% 攻击力的火属性持续伤害，持续 2 回合（50% 基础概率按命中算）',
)

# ② 卡芙卡 E1：易伤只挂追加攻击的目标
F.has('r:100501', '天赋触发追加攻击时，有#的基础概率使目标受到的持续伤害提高#')
rename_eff(
    1005, 'E1：天赋触发追加攻击时', r=1,
    tg='efirst',
    n='E1：天赋触发追加攻击时使追加攻击的目标受到的持续伤害 +30%，持续 2 回合',
)

# ③ 瓦尔特【失重】速度 −5% 默认开
F.has('1100404', '处于【失重】状态下的敌方目标防御力降低#，速度降低#')
rename_eff(
    1004, '【强化版】天赋：【失重】的敌人速度',
    n='【强化版】天赋：处于【失重】状态下的敌方目标速度 −5%，持续 2 回合（按敌人自己的回合；终结技必定挂上【失重】，默认开启）',
    drop_off=True, off0=True,
)

log = """<li><b>2026-11-15（差异清单第 1 批）：tv 116（tools/fix116.py）</b>。按仓库的《差异清单》逐条改，第一批三条都是「和官方原文对不上」的目标 / 默认开关：① <b>姬子</b>行迹星火：原文「施放攻击后…使敌方目标陷入灼烧」指的是<b>这次攻击打到的敌人</b>，原来一律挂在敌方全体（单体普攻也给全体挂），现在单体只挂主目标、扩散挂主目标和相邻、群攻挂全体。② <b>卡芙卡</b> E1：原文「天赋触发追加攻击时，有 100% 的基础概率使<b>目标</b>受到的持续伤害提高 30%」，原来挂在敌方全体，现在只挂追加攻击的目标。③ <b>瓦尔特【强化版】</b>天赋：原文「处于【失重】状态下的敌方目标…速度降低 5%」，【失重】是终结技必定挂上的、不是概率，这条从默认关闭改成默认开启。<b>对已有配置</b>：姬子、卡芙卡这两条是伤害变（敌人少了灼烧 / 易伤，数字降一点，行动轴不变）；瓦尔特那条会让敌人慢 5%，带瓦尔特并且开过终结技的队伍行动顺序会变。旧配置载入时自动换成新写法；原来手动关掉的效果仍然关着（瓦尔特这条按原文改成默认开）。</li>"""

record = """2026-11-15（差异清单第 1 批）：tv 116（tools/fix116.py）。改：姬子行迹星火挂灼烧改 ehit、卡芙卡 E1 易伤改 efirst、瓦尔特天赋【失重】速度 −5% 默认开（off0）。
  未改 / 存疑：卡芙卡 E1 的 30% 走持续伤害乘区（和原文一致）；瓦尔特这条没按敌人身上是否还有【失重】再判断（终结技必定挂、时长一致，暂不另做）；姬子「50% 基础概率」仍按命中算（随机类统一按命中，见差异清单一）。"""

