"""tv 68：每日校对（2026-11-11）—— 加拉赫 1301、知更鸟 1309、阿格莱雅 1402（上次校对 10-28 / 10-30，最久）。
用法：python3 tools/fix68.py index.html <官方 json 目录>
- 加拉赫：终结技“将下一次普攻强化为【酒花奔涌】”做成状态【酒花奔涌】+ x.ebSt（选普攻时自动变强普，施放后移除）。
- 知更鸟：战技增伤“持续 3 回合，知更鸟每回合开始时持续回合数减 1”做成状态【翎之咏叹调】（ts start）；
  【协奏】做成状态（倒计时登场获得、离场移除）；E2“处于【协奏】状态时我方全体速度 +16%”跟着【协奏】（原来是开大后 1 回合）；
  终结技攻击力固定值 3 魂 200 → 230（官方参数 12 级）。
- 阿格莱雅：忆灵天赋速度 +55 在 3 魂（忆灵天赋 +1 级，7 级）是 57.2；终结技【至高之姿】每层速度 15% 在 5 魂（终结技 12 级）是 16%。
"""
import sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from fixlib import Fix
F = Fix(sys.argv[1], 68, sys.argv[2])
C, has, hast = F.C, F.has, F.hast
cp = lambda e: dict(e)

# ================= 加拉赫 1301 =================
cid = 1301
has(130103, '使敌方全体陷入【酩酊】状态，持续#回合，同时对敌方全体造成等同于加拉赫#攻击力的火属性伤害，并将下一次普攻强化为【酒花奔涌】')
has(130108, '对指定敌方单体造成等同于加拉赫#攻击力的火属性伤害')
new = []
for e in C[cid]['eff']:
    new.append(e)
    if e.get('n') == '终结技：敌方全体陷入【酩酊】，持续 2 回合':
        new.append({'y': 'state', 't': 'ult', 'tg': 'self', 'sn': '酒花奔涌', 'v': 1, 'd': 0, 'n': '终结技：下一次普攻强化为【酒花奔涌】（平时选普攻时自动变成强普）'})
    if e.get('n', '').startswith('行迹敬请干杯'):
        new.append({'y': 'state', 't': 'ebasic', 'tg': 'self', 'sn': '酒花奔涌', 'v': 0, 'n': '【酒花奔涌】施放后，普攻恢复成普通普攻'})
assert len(new) == len(C[cid]['eff']) + 2
F.rebuild(cid, new, x={'ebSt': '酒花奔涌'})

# ================= 知更鸟 1309 =================
cid = 1309
has(130902, '使我方全体造成的伤害提高#，持续#回合，知更鸟每回合开始时持续回合数减#')
has(130903, '我方全体攻击力提高，提高数值等同于知更鸟攻击力的#+#点')
has('r:130902', '处于【协奏】状态时，我方全体速度提高#')
p3 = F.prm('130903')
assert p3[9][2] == 200 and p3[11][2] == 230 and abs(p3[11][0] - 0.2432) < 1e-9, (p3[9], p3[11])
new, ren = [], {}
for e in C[cid]['eff']:
    e = cp(e)
    if e.get('bk') == 'sk' and e.get('m') == 'dmg':
        new.append({'y': 'state', 't': 'skill', 'tg': 'self', 'sn': '翎之咏叹调', 'v': 1, 'd': 3, 'ts': 1, 'n': '战技：获得【翎之咏叹调】，持续 3 回合（知更鸟每回合开始时 −1）'})
        o = e['n']; e.update({'d': 0, 'bk': 'st:翎之咏叹调', 'n': '战技：【翎之咏叹调】期间我方全体造成的伤害 +50%（3 魂 55%）'}); ren[o] = e['n']
    elif e.get('bk') == 'xz' and e.get('t') == 'smOn':
        o = e['n']; e['lx'] = {'flat': [200, 230]}
        e['n'] = '终结技：【协奏】期间我方全体攻击力 +知更鸟攻击力的 22.8% + 200（3 魂 24.32% + 230）'; ren[o] = e['n']
    if e.get('n') == '终结技：进入协奏，倒计时上场（速度 90）':
        new.append(e)
        new.append({'y': 'state', 't': 'smOn', 'sk': 'concert', 'tg': 'self', 'sn': '协奏', 'v': 1, 'd': 0, 'n': '终结技：进入【协奏】（倒计时登场时）'})
        continue
    if e.get('n') == '终结技：倒计时行动后退出协奏并立即行动':
        new.append({'y': 'state', 't': 'smEnd', 'sk': 'concert', 'tg': 'self', 'sn': '协奏', 'v': 0, 'n': '终结技：倒计时回合开始时退出【协奏】'})
    new.append(e)
assert len(new) == len(C[cid]['eff']) + 3, len(new)
F.rebuild(cid, new, rename=ren)
e2 = F.eid(cid, 2)
sp = [x for x in e2['eff'] if x['y'] == 'spd']; assert len(sp) == 1
sp[0].update({'d': 0, 'bk': 'st:协奏', 'n': 'E2 两者的午茶：处于【协奏】状态时我方全体速度 +16%（退出【协奏】时取消）'})

# ================= 阿格莱雅 1402 =================
cid = 1402
has(1140203, '攻击处于【间隙织线】状态的敌人后，使自身的速度提高#点，该效果最多叠加#层')
has(140203, '每层使自身速度提高#')
pm, pu = F.prm('1140203'), F.prm('140203')
assert pm[5][0] == 55 and abs(pm[6][0] - 57.2) < 1e-9 and abs(pu[9][0] - 0.15) < 1e-9 and abs(pu[11][0] - 0.16) < 1e-9
lvup = {x['id']: x['num'] for x in F.RK['140203']['level_up_skills']}; assert lvup.get('1140203') == 1
lvup = {x['id']: x['num'] for x in F.RK['140205']['level_up_skills']}; assert lvup.get('140203') == 2
new, ren = [], {}
for e in C[cid]['eff']:
    e = cp(e)
    if e.get('y') == 'spd' and e.get('bk') == 'gspd':
        assert e['v'] == 55; e['lv'] = [3, 57.2]; o = e['n']; e['n'] = o + '（3 魂 57.2）'; ren[o] = e['n']
    elif e.get('y') == 'spd' and e.get('bk') == 'aspd' and e.get('v'):
        assert e['v'] == 15; e['lv'] = [5, 16]; o = e['n']; e['n'] = o + '（5 魂 16%）'; ren[o] = e['n']
    new.append(e)
assert len(ren) == 4, ren
F.rebuild(cid, new, rename=ren)
e4 = F.eid(cid, 4)
for x in e4['eff']:
    if x.get('bk') == 'gspd': x['lv'] = [3, 57.2]; x['n'] += '（3 魂起每层 57.2）'
    elif x.get('bk') == 'aspd': x['lv'] = [5, 16]; x['n'] += '（5 魂起每层 16%）'
    else: raise AssertionError(x)

