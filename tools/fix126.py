"""tv 126（2026-11-15）：差异清单第 11 批
银狼 1006 行迹「生成」：【缺陷】持续时间 +1 回合（模板里已经有"含行迹生成 +1"）；
  每当有敌方目标的弱点被击破时，对该目标植入 1 个随机【缺陷】——这条模板里没有。
  按页面已建模的那种【缺陷】（防御力 −12%）挂上去，持续 4 回合（3 + 行迹 1）。

用法：python _src/fix126.py
"""
import sys
sys.path.insert(0, '_src')
from fixlib import Fix

TV = 126
F = Fix('星铁行动轴.html', TV, '_src')

F.hast(1006, '生成', '每当有敌方目标的弱点被击破时，银狼有#的基础概率对该目标植入#个随机【缺陷】')

c = F.C[1006]
before = [e['n'] for e in c['eff'] if e.get('y') != 'info']
c['eff'].append({
    'y': 'dbuf', 't': 'break', 'tg': 'evt', 'm': 'defRed', 'v': 12, 'lv': [3, 13.2], 'd': 4, 'bk': 'qx',
    'n': '行迹生成：每当有敌方目标的弱点被击破时，对该目标植入 1 个随机【缺陷】（按防御力 −12% 那种；3 魂 13.2%），持续 4 回合（含行迹 +1）',
})
fx = F.FIX.setdefault('1006', {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})
for n in before:
    if n not in fx['drop']:
        fx['drop'].append(n)
fx['add'].append(c['eff'][-1]['n'])
fx['trig'][c['eff'][-1]['n']] = 'break'

log = """<li><b>2026-11-15（差异清单第 11 批）：tv 126（tools/fix126.py）</b>。<b>银狼</b>行迹「生成」后半句「每当有敌方目标的弱点被击破时，银狼对该目标植入 1 个随机【缺陷】」原来没做（前半句「【缺陷】持续时间 +1 回合」模板里已经有）。现在敌方弱点被击破时给该敌人挂上页面已建模的那种【缺陷】（防御力 −12%，3 魂 13.2%），持续 4 回合。<b>对已有配置</b>：要放了带韧性的敌人、并且真的被击破才会触发（会多一个减防），没击破或没放敌人卡时完全不变。</li>"""

record = """2026-11-15（差异清单第 11 批）：tv 126（tools/fix126.py）。改：银狼补行迹「生成」的击破植入【缺陷】（dbuf / break / tg evt / defRed 12 / d 4）。
  未改 / 存疑：游戏里 3 种【缺陷】（防御 / 速度 / 攻击）随机一种，这里固定按防御 −12% 那种算（和模板里已有的【缺陷】写法一致）；「攻击力 −?」那种没建模。"""

F.finish('差异清单第 11 批（银狼行迹生成：击破时植入【缺陷】）', log, record)
print('done tv', TV)
