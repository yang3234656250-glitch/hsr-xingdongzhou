e2 = [x for x in F.eid(1313, 2)['eff'] if x.get('bk') == 'e2']
assert len(e2) == 1 and e2[0]['tg'] == 'ultpick'
e2[0].update({'tg': 'ultpickm', 'alv': 1, 'n': 'E2 笃信补完微缺：【蒙福者】（目标及其忆灵）造成的伤害 +30%（星期日倒下时解除）'})

