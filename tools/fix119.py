"""tv 119（2026-11-15）：差异清单第 4 批
① 杰帕德 1104：行迹统领（不屈之身触发后回满能量）、E6 不屈的决意（立即行动 + 额外回复 50% 生命上限）
   原来挂在「受到攻击时」触发、默认关；天赋本身是「受到致命攻击时」，改成跟着天赋（fatal）并默认开
② 大丽花 1321：行迹又一场葬礼的数值补全——「其他角色击破特攻 + 大丽花击破特攻的 24% + 50%」
   原来只算了 +50%，现在按大丽花面板击破特攻算 24%

用法：python _src/fix119.py
"""
import sys
sys.path.insert(0, '_src')
from fixlib import Fix

TV = 119
F = Fix('星铁行动轴.html', TV, '_src')


def rename_eff(cid, frag, r=None, off0=None, drop_off=False, **chg):
    e = F.eff(cid, frag, r=r)
    old = e['n']
    trig = e.get('t')
    e.update(chg)
    if drop_off:
        e.pop('off', None)
    new = e['n']
    fx = F.FIX.setdefault(str(cid), {'drop': [], 'trig': {}, 'map': {}, 'add': [], 'sm': {}})
    fx['drop'].append(old)
    fx['add'].append(new)
    fx['trig'][old] = trig
    if new != old:
        fx['map'][old] = new
    if off0:
        fx.setdefault('off0', []).append(new)
    return old, new


# ---------------- ① 杰帕德 ----------------
F.has('1104102', '【不屈之身】触发后，杰帕德的能量立即恢复至#')
rename_eff(
    1104, '行迹统领',
    t='fatal',
    n='行迹统领：【不屈之身】触发后，杰帕德的能量立即恢复至 100%（跟着天赋触发，默认开启）',
    drop_off=True, off0=True,
)

F.has('r:110406', '触发天赋时杰帕德立即行动，且当前生命值的回复量额外增加自身生命上限的#')
r6 = F.eid(1104, 6)
for e in r6['eff']:
    if e.get('t') == 'hit':
        e['t'] = 'fatal'
        e.pop('off', None)
        e['n'] = e['n'].replace('（和天赋那条一起启用）', '（跟着天赋触发，默认开启）')

# ---------------- ② 大丽花 ----------------
F.has('1321101', '使其他角色的击破特攻提高，提高数值等同于#大丽花的击破特攻+#')
rename_eff(
    1321, '行迹又一场葬礼',
    srcS='be', v=24, hf=50,
    n='行迹又一场葬礼：进入战斗时其他角色击破特攻 +（大丽花击破特攻的 24% + 50%），持续 1 回合（按卡片面板击破特攻；受到治疗 / 护盾后再次触发、持续 3 回合那部分没做）',
)

log = """<li><b>2026-11-15（差异清单第 4 批）：tv 119（tools/fix119.py）</b>。两条都是「数值 / 触发条件对不上」：① <b>杰帕德</b>：行迹统领（【不屈之身】触发后能量回满）和 E6 不屈的决意（触发天赋时立即行动 + 额外回复 50% 生命上限）原来挂在「受到攻击时」、还要手动开，但天赋本身是「受到致命攻击时」触发，所以这三条以前基本不会生效；现在改成跟着天赋（fatal）触发并默认开启。② <b>大丽花</b>行迹又一场葬礼：原文「其他角色击破特攻 + 大丽花击破特攻的 24% + 50%」，页面只算了 +50%，现在按大丽花面板击破特攻把 24% 那部分算进去。<b>对已有配置</b>：杰帕德这条要敌人真打出致命攻击（开了「敌人打我方掉血」）才会变，而且会给他「立即行动」，行动轴可能变；大丽花这条只影响带她时的击破特攻数值（击破伤害），伤害显示和行动轴不变。</li>"""

record = """2026-11-15（差异清单第 4 批）：tv 119（tools/fix119.py）。改：杰帕德行迹统领 + E6 两条由 hit 改 fatal、默认开（off0）；大丽花行迹又一场葬礼加 ss be / v 24 / hf 50。
  未改 / 存疑：大丽花「受到队友治疗或护盾后再次触发，持续 3 回合」没做；杰帕德 E6 的「立即行动」按 advance 100% 实现（行动值直接到 0），和游戏里的「立即行动」语义一致。"""

F.finish('差异清单第 4 批（杰帕德不屈之身系列 / 大丽花又一场葬礼）', log, record)
print('done tv', TV)
